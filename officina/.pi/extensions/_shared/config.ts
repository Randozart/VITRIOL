// Environment knobs, declared in ONE place (2026-11-18).
//
// Officina reads 162 `OFFICINA_*` variables across its extensions. Each one was a
// string literal at the point of use: no registry, no default in one place, no
// way to answer "what can I turn off?". That is the third untyped channel
// (after `globalThis` and widget keys) that made the codebase hard to reason
// about.
//
// This module does not re-plumb 160 call sites (that would be a large, risky
// change for no behaviour gain). It makes the surface VISIBLE and RATCHETED:
//   - `KNOBS` is the frozen inventory, each entry with a one-line purpose;
//   - new code should read the knob through `env.*` below;
//   - `config.test.ts` fails when a source uses a knob that is not declared
//     here, so the inventory cannot drift.
//
// Kill switches (documented so an operator can find them):
//   OFFICINA_NO_CLAIMS=1        disable cross-session file claims
//   OFFICINA_NO_PREDICTIONS=1   disable the composer prediction row
//   OFFICINA_NO_ACTIVE_FILES=1  disable hot-file tracking
//   OFFICINA_NO_OVERFLOW=1      disable adaptive routing entirely
//   OFFICINA_ROUTE_MODE=off     advisory/enforced cloud routing off

/** Read a knob as a string (empty string when unset). */
export function envString(name: string, env: NodeJS.ProcessEnv = process.env): string {
  return (env[name] ?? "").trim();
}

/** Read a knob as a boolean: "1"/"true"/"on"/"yes" are true. */
export function envFlag(name: string, env: NodeJS.ProcessEnv = process.env): boolean {
  return /^(1|true|on|yes)$/i.test(envString(name, env));
}

/** Read a knob as a number, falling back when unset or unparseable. */
export function envNumber(
  name: string,
  fallback: number,
  env: NodeJS.ProcessEnv = process.env,
): number {
  const raw = envString(name, env);
  if (!raw) return fallback;
  const value = Number(raw);
  return Number.isFinite(value) ? value : fallback;
}

