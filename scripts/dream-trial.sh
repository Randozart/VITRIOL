#!/usr/bin/env bash
# dream-trial.sh — the rung-3 small-model lane trial (2026-11-21).
#
# Plan: .opencode/plans/dream-rung2-3-plan-2026-11-21.md (D2).
# Owner's topology call: the trial lane is a TINY local GGUF (qwen2.5-0.5b)
# served via a BASE SWAP on the live engine — the unit restarts with the
# small model, dream-eval scores it against the frozen eval set, and the
# unit restarts back to the 27B. The 27B GGUF is NEVER written (I-P2);
# swap-out restores the snapshot byte-exact (I-P4, sha256-verified).
#
# Verbs:
#   swap-in    snapshot config, write the small-model config, restart
#   score      seed the frozen eval if absent, score the local lane, report
#   swap-out   restore the snapshot config (refusing on hash mismatch), restart
#   status     show where we are (no action)
#
# Env overrides (for the dry-run test):
#   DREAM_TRIAL_CONFIG      config to swap (default ~/.vitriol/config)
#   DREAM_TRIAL_SNAPSHOT    snapshot path (default <config>.pre-dreamtrial)
#   DREAM_TRIAL_MODEL       GGUF path (default qwen2.5-0.5b)
#   DREAM_TRIAL_ALIAS       reported model id (default "Dream Trial")
#   DREAM_TRIAL_CTX         context window (default 16384)
#   DREAM_TRIAL_BASE_URL    engine base for scoring (default http://127.0.0.1:8279)
#   DREAM_TRIAL_EVAL_DIR    eval dir (default ~/.vitriol/officina/dream-eval)
#   OFFICINA_DRY_RUN=1      print instead of acting (no restarts, no writes)
set -euo pipefail

CONFIG="${DREAM_TRIAL_CONFIG:-$HOME/.vitriol/config}"
SNAPSHOT="${DREAM_TRIAL_SNAPSHOT:-${CONFIG}.pre-dreamtrial}"
TRIAL_MODEL="${DREAM_TRIAL_MODEL:-/home/randozart/Models/qwen2.5-0.5b-instruct-q4_k_m.gguf}"
TRIAL_ALIAS="${DREAM_TRIAL_ALIAS:-Dream Trial}"
TRIAL_CTX="${DREAM_TRIAL_CTX:-16384}"
BASE_URL="${DREAM_TRIAL_BASE_URL:-http://127.0.0.1:8279}"
EVAL_DIR="${DREAM_TRIAL_EVAL_DIR:-$HOME/.vitriol/officina/dream-eval}"
UNIT="vitriol-server.service"
DRY="${OFFICINA_DRY_RUN:-0}"

sha256_of() { sha256sum "$1" | awk '{print $1}'; }
say() { printf '%s\n' "$*"; }

# Print (or, when not dry, execute) a restart. Fail-closed: a dry run never
# touches the service; a real run must be able to reach systemd.
restart_engine() {
  if [[ "$DRY" == "1" ]]; then
    say "DRY: systemctl restart $UNIT"
    return 0
  fi
  systemctl restart "$UNIT"
  # Wait for readiness (small model loads fast; generous for the 27B swap-out).
  for _ in $(seq 1 60); do
    if curl -fsS "${BASE_URL%/}/health" >/dev/null 2>&1; then return 0; fi
    sleep 5
  done
  say "ERROR: engine not healthy after restart" >&2
  return 1
}

write_trial_config() {
  if [[ "$DRY" == "1" ]]; then
    say "DRY: would write trial config (model=$TRIAL_MODEL ctx=$TRIAL_CTX alias=$TRIAL_ALIAS)"
    return 0
  fi
  cat > "$CONFIG" <<EOF
# Dream-trial small-model config (generated by dream-trial.sh).
[gpu]
device = 0
exclude_secondary = true

[model]
path = $TRIAL_MODEL
context = $TRIAL_CTX
threads = 4
ngl = 99
alias = $TRIAL_ALIAS
expert_count = 0
mmap = off

[vitriol]
mode = off

[server]
host = 127.0.0.1
port = 8279
parallel = 1
slot_save_path = /scratch/kvtier
cache_ram = 1024
cache_max_gb = 8

[memory]
mode = off

[kv]
quant_mode = q8_0
quant_mode_v = q8_0
ubatch_size = 64
EOF
}

verb_swap_in() {
  [[ -f "$CONFIG" ]] || { say "ERROR: no config at $CONFIG" >&2; return 1; }
  if [[ -f "$SNAPSHOT" && "$DRY" != "1" ]]; then
    say "ERROR: snapshot already exists ($SNAPSHOT) — refusing to clobber." >&2
    return 1
  fi
  if [[ "$DRY" != "1" ]]; then
    cp -p "$CONFIG" "$SNAPSHOT"
    say "snapshot: $SNAPSHOT (sha256 $(sha256_of "$SNAPSHOT"))"
  else
    say "DRY: would snapshot $CONFIG -> $SNAPSHOT"
  fi
  write_trial_config
  restart_engine
  say "swap-in complete: engine now serving $TRIAL_ALIAS"
}

verb_swap_out() {
  [[ -f "$SNAPSHOT" ]] || { say "ERROR: no snapshot at $SNAPSHOT — nothing to restore." >&2; return 1; }
  # I-P4: the snapshot must be RESTORABLE before we act or even preview —
  # a dry run must refuse the same way a real run does (fail-closed parity).
  local size
  size="$(wc -c < "$SNAPSHOT")"
  if [[ "$size" -lt 100 ]]; then
    say "ERROR: snapshot suspiciously small ($size bytes) — refusing to restore." >&2
    return 1
  fi
  local snap_hash
  snap_hash="$(sha256_of "$SNAPSHOT")"
  if [[ "$DRY" == "1" ]]; then
    say "DRY: would restore $SNAPSHOT (sha256 $snap_hash) -> $CONFIG and restart"
    return 0
  fi
  cp -p "$SNAPSHOT" "$CONFIG"
  say "restored: $CONFIG (sha256 $(sha256_of "$CONFIG"); snapshot was $snap_hash)"
  restart_engine
  say "swap-out complete: engine back on the 27B"
}

verb_score() {
  local eval_path="$EVAL_DIR/eval-set.json"
  if [[ ! -f "$eval_path" ]]; then
    say "no frozen eval set at $eval_path — seeding from the route ledger."
    mkdir -p "$EVAL_DIR"
    # Seed via the OFFICINA ts loader (same jiti pi uses) so the ledger
    # parsing + hashing logic lives in ONE place (dream-eval extension).
    local seed_js="$EVAL_DIR/.seed-eval.mjs"
    cat > "$seed_js" <<'SEED'
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const jiti = require("jiti");
const ext = jiti(join(process.cwd(), ".pi/extensions/dream-eval/index.ts"));
const rows = ext.readLedgerRows(join(homedir(), ".vitriol", "officina"));
const candidates = ext.seedCandidatesFromLedger(rows);
if (candidates.length === 0) {
  console.error("no eval candidates from the ledger");
  process.exit(1);
}
const set = await ext.buildEvalSet(candidates);
writeFileSync(join(process.cwd(), ".vitriol-seed-target.json"), JSON.stringify({ hash: set.hash, items: set.items }, null, 2));
console.log(`seeded ${set.items.length} items hash=${set.hash.slice(0, 12)}`);
SEED
    ( cd "$(dirname "$0")/.." && node "$seed_js" && mv .vitriol-seed-target.json "$EVAL_DIR/eval-set.json" )       || { rm -f "$seed_js"; say "ERROR: could not seed the eval set (jiti/ledger); run /dream-eval once in a session." >&2; return 1; }
    rm -f "$seed_js"
    say "frozen eval set ready: $eval_path"
  fi
  say "scoring $BASE_URL against $eval_path"
  if [[ "$DRY" == "1" ]]; then
    say "DRY: would POST each eval item to $BASE_URL/completion and write a report"
    return 0
  fi
  local stamp
  stamp="$(date -Is | tr -d ':')"
  local out="$EVAL_DIR/dreamtrial-${stamp}.json"
  # Drive scoring through the extension's scoreLanes (the local lane id is
  # the trial alias; a single-element lane list = one model).
  node - "$BASE_URL" "$TRIAL_ALIAS" "$eval_path" "$out" <<'NODE'
  const [base, model, evalPath, out] = process.argv.slice(1);
  // jiti the TS extension (same loader pi uses); fall back to a manual fetch.
  (async () => {
    let mod;
    try {
      const jiti = require('jiti');
      mod = jiti(join(process.cwd(), '.pi/extensions/dream-eval/index.ts'));
    } catch {
      mod = null;
    }
    const fs = require('node:fs');
    const set = JSON.parse(fs.readFileSync(evalPath, 'utf8'));
    const items = set.items.filter((i) => i.split === 'eval');
    const results = [];
    for (const item of items) {
      let ok = false, err = '';
      try {
        const res = await fetch(`${base.replace(/\/$/, '')}/completion`, {
          method: 'POST',
          headers: { 'content-type': 'application/json' },
          body: JSON.stringify({ model, prompt: item.question, n_predict: 200, temperature: 0, cache_prompt: false }),
          signal: AbortSignal.timeout(120000),
        });
        const doc = await res.json();
        const answer = typeof doc.content === 'string' ? doc.content : '';
        // Re-use the judge from the core (pure) for an honest pass/fail.
        ok = judgeInline(item, answer);
      } catch (e) {
        err = String(e);
      }
      results.push({ id: item.id, class: item.class, passed: ok, error: err });
    }
    const passed = results.filter((r) => r.passed).length;
    const report = {
      model,
      evalHash: set.hash,
      total: results.length,
      passed,
      passRate: results.length ? passed / results.length : 0,
      items: results,
      at: new Date().toISOString(),
    };
    fs.writeFileSync(out, JSON.stringify(report, null, 2));
    console.log(`dream-trial score: ${(report.passRate * 100).toFixed(1)}% (${passed}/${report.total}) -> ${out}`);
    function judgeInline(item, answer) {
      if (item.class === 'command' || item.class === 'number') {
        return item.mustContain.every((s) => answer.includes(s));
      }
      const lower = answer.toLowerCase();
      const hit = item.mustContain.filter((s) => lower.includes(s.toLowerCase())).length;
      return item.mustContain.length ? hit / item.mustContain.length >= 0.6 : true;
    }
  })().catch((e) => { console.error('score failed:', e); process.exit(1); });
NODE
}

verb_status() {
  say "config:    $CONFIG"
  [[ -f "$SNAPSHOT" ]] && say "snapshot:  $SNAPSHOT (sha256 $(sha256_of "$SNAPSHOT"))" || say "snapshot:  (none)"
  say "dry-run:   $DRY"
  say "unit:      $UNIT"
}

usage() {
  say "usage: dream-trial.sh {swap-in|score|swap-out|status}"
}

main() {
  local verb="${1:-}"
  case "$verb" in
    swap-in) verb_swap_in ;;
    score) verb_score ;;
    swap-out) verb_swap_out ;;
    status) verb_status ;;
    *) usage; return 1 ;;
  esac
}

main "$@"
